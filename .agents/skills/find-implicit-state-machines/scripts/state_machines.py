#!/usr/bin/env python3
"""state_machines.py — the deterministic half of /find-implicit-state-machines.

    state_machines.py scan [--path <p>]... [--limit N]
    state_machines.py signals
    state_machines.py check [<findings.json>] [--write]
    state_machines.py tla [<findings.json>] --name <machine> [--out DIR]

Paths resolve from the repository root (git's top level, else the working
directory), so every command behaves the same from any subdirectory. The
findings file defaults to <root>/.jplugin/state-machines/findings.json.

scan   ranks code files by state-like patterns (references/signals.md) and
       prints {"head", "files_scanned", "candidates": [...]}, score desc then
       path asc. Inside git it lists files with `git ls-files --cached --others
       --exclude-standard`, so .gitignore is honoured; outside git it walks the
       tree. Vendor, generated, test, fixture and non-code files never rank.
check  validates a findings file against the schema in SKILL.md, refusing a
       state, file, cited line or field that is not there, and prints one
       summary line per machine. --write stores the computed `coverage` and
       `flags`; without it, stored values that no longer match are refused.
tla    writes a TLA+ skeleton and TLC config for one machine.
signals prints the signal weights and exclusion lists scan applies, as JSON.

Standard library only. Read-only except for the two files `check --write` and
`tla` are asked to write. Exit 0 ok, 1 invalid findings, 2 usage or I/O error.
"""
import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import PurePosixPath

DEFAULT_LIMIT = 40
SAMPLES_PER_FILE = 5
MIN_SIGNAL_KINDS = 2
MAX_FILE_BYTES = 1_000_000
MAX_LINE_CHARS = 500
GENERATED_MARKERS = ("@generated", "DO NOT EDIT", "Code generated", "auto-generated", "autogenerated")
GENERATED_HEAD_LINES = 5
#: Third-party code that is often committed, so skipped even inside git.
VENDOR_DIRS = {"node_modules", "vendor", "third_party", "third-party", "bower_components", "Pods",
               ".venv", "venv", "__pycache__", ".git", ".jplugin"}
#: Build output: .gitignore decides inside git (a skill called `build` is source);
#: the plain walk outside git has no .gitignore, so it skips these by name.
OUTPUT_DIRS = {"dist", "build", "out", "target", "coverage", ".next", ".nuxt"}
COMMENT_LINE = re.compile(r"^\s*(?:#(?!!)|//|/\*|\*|--\s|;;)")
TEST_DIRS = {"test", "tests", "spec", "__tests__", "fixtures", "__fixtures__", "testdata", "e2e"}
TEST_NAME = re.compile(r"(^test_.*\.py$|_test\.\w+$|\.(test|spec)\.\w+$|Tests?\.\w+$|_spec\.rb$)")
CODE_EXTENSIONS = {".py", ".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx", ".vue", ".svelte", ".go",
                   ".rs", ".java", ".kt", ".kts", ".scala", ".swift", ".m", ".rb", ".php", ".cs",
                   ".fs", ".c", ".h", ".cc", ".cpp", ".hpp", ".sh", ".bash", ".zsh", ".ex", ".exs",
                   ".erl", ".clj", ".dart", ".lua", ".pl", ".awk", ".elm", ".hs", ".ml", ".zig"}
SKIPPED_SUFFIXES = (".min.js", ".min.css", ".bundle.js", ".pb.go", "_pb2.py", ".g.dart", ".d.ts")

MODAL = r"(?:state|status|phase|mode|stage|lifecycle)"
#: A boolean-looking name: isReady / is_ready / in_block / OWNS_LOCK / build_done.
FLAG = (r"\b(?:(?:is|has|was|did|should|can|in|owns)(?:_[a-z]|[A-Z])\w*"
        r"|(?i:(?:is|has|was|did|in|owns)_\w+|\w+_(?:done|started|running|ready|active|pending"
        r"|dirty|seen|locked|open|closed|enabled|failed)))\b")
#: name → (weight, pattern). The one place a signal is defined; signals.md explains each.
SIGNALS = {
    "modal-assign": (3, re.compile(r"(?i)[\w.$]*" + MODAL + r"\b\s*(?::(?!:)|:=|=(?!=))\s*['\"]?[\w-]+")),
    "modal-compare": (3, re.compile(r"(?i)[\w.$]*" + MODAL + r"\b['\"]?\s*(?:===?|!==?|-eq\b|-ne\b|\bis\b)\s*['\"]?\w")),
    "modal-switch": (4, re.compile(r"(?i)\b(?:switch|match|case)\s*\(?\s*['\"]?\$?\{?[\w.$]*" + MODAL + r"\b")),
    "state-enum": (4, re.compile(r"\b(?:enum|class|type|interface)\s+\w*(?:State|Status|Phase|Mode|Stage)\b")),
    "transition-call": (3, re.compile(r"\bset(?:State|Status|Phase|Mode|Stage)\s*\(|\.(?:transition|transitionTo|dispatch|send)\s*\(|(?i:\b(?:transition|advance|enter)_?(?:to|state)\w*\s*\()")),
    "flag-assign": (2, re.compile(FLAG + r"\s*(?::(?!:)|=(?!=))\s*(?:true|false|True|False|0|1)\b")),
    "flag-guard": (2, re.compile(r"\b(?:if|while|elif|unless)\b\s*[(\[]*\s*(?:!|not\s+)?['\"]?\$?\{?[\w.$]*?" + FLAG)),
    "toggle": (2, re.compile(r"\b(\w+)\s*=\s*!\s*\1\b")),
    "marker-file": (2, re.compile(r"(?i)(?:\btouch\s|\brm\s|\s-[ef]\s|\.exists\(|\.unlink\(|\bmkdir\s)[^\n]*?(?:lock|state|marker|pending|stamp|sentinel|guard|claim|\.done)\w*")),
    "event-handler": (1, re.compile(r"\baddEventListener\s*\(|\.on\(\s*['\"]|\bon[A-Z]\w*\s*[=:(]|\btrap\s+['\"]|@\w+\.(?:on|route|subscribe)\b")),
    "async-order": (1, re.compile(r"\bawait\b|\.then\s*\(|Promise\.(?:all|race)\b|asyncio\.(?:gather|create_task)\b|\bsetTimeout\s*\(")),
}


FINDING_FIELDS = ("name", "files", "states", "transitions", "entry", "exit", "tested", "tests",
                  "confidence", "hidden")
EDGE_FIELDS = ("from", "to", "via", "tested")
CONFIDENCE = ("HIGH", "MEDIUM", "LOW")
TESTED = ("TESTED", "UNTESTED")
WIDE_STATES = 3
LOW_COVERAGE = 0.5
#: `path:12` or `path:12-20` inside prose; `via` must carry at least one, root-relative.
CITATION = re.compile(r"(?<![\w/.-])([\w.-]+(?:/[\w.-]+)*):(\d+)(?:-(\d+))?(?![\w-])")
#: The skill's one output directory, relative to the repository root.
OUTPUT_DIR = ".jplugin/state-machines"
FINDINGS_PATH = OUTPUT_DIR + "/findings.json"
TLA_DIR = OUTPUT_DIR + "/tla"
#: The operators the TLC config names; render_tla defines each.
TLA_INIT, TLA_NEXT, TLA_INVARIANTS = "Init", "Next", ("TypeOK", "IntendedOnly")


class Invalid(Exception):
    """The findings file breaks the schema; exit 1."""


class UsageError(Exception):
    """A path, flag or file the command cannot use; exit 2."""


def git(*args):
    try:
        done = subprocess.run(["git", *args], capture_output=True, text=True,
                              encoding="utf-8", check=False)
    except OSError:
        return None
    return done.stdout if done.returncode == 0 else None


class Repo:
    """Where the repository root is, decided once: git's top level, else the working directory.

    Every path the commands read, write or report is root-relative, so a command
    run from a subdirectory sees the same files as one run from the root.
    """

    def __init__(self):
        top = git("rev-parse", "--show-toplevel")
        self.in_git = top is not None
        self.root = os.path.realpath(top.strip() if top else os.getcwd())

    def path(self, relative):
        return os.path.join(self.root, relative)

    def from_cwd(self, given):
        """A user-given path, as root-relative POSIX."""
        return os.path.relpath(os.path.realpath(given), self.root).replace(os.sep, "/")


# ── scan ────────────────────────────────────────────────────────────────────

def listed_files(repo):
    """Root-relative paths: git's view inside a work tree, else a walk of the root."""
    if repo.in_git:
        listing = git("-C", repo.root, "ls-files", "-z", "--cached", "--others", "--exclude-standard")
        if listing is None:
            raise UsageError("git ls-files failed")
        return sorted(p for p in listing.split("\0") if p)
    found = []
    for root, dirs, files in os.walk(repo.root):
        dirs[:] = sorted(d for d in dirs if d not in VENDOR_DIRS | OUTPUT_DIRS)
        found.extend(os.path.relpath(os.path.join(root, f), repo.root).replace(os.sep, "/") for f in files)
    return sorted(found)


def is_scannable(path):
    pure = PurePosixPath(path)
    parts = set(pure.parts[:-1])
    if parts & VENDOR_DIRS or parts & TEST_DIRS or TEST_NAME.search(pure.name):
        return False
    return pure.suffix in CODE_EXTENSIONS and not path.endswith(SKIPPED_SUFFIXES)


def read_code(absolute):
    """The file's lines, or None for a generated, minified, binary or unreadable file."""
    try:
        if os.path.getsize(absolute) > MAX_FILE_BYTES:
            return None
        with open(absolute, "rb") as source:
            raw = source.read()
    except OSError:
        return None
    if b"\0" in raw:
        return None
    lines = raw.decode("utf-8", errors="replace").splitlines()
    head = "\n".join(lines[:GENERATED_HEAD_LINES])
    if any(marker in head for marker in GENERATED_MARKERS):
        return None
    if any(len(line) > MAX_LINE_CHARS for line in lines):
        return None
    return lines


def score_file(path, lines):
    counts, first = {}, {}
    for number, line in enumerate(lines, 1):
        if COMMENT_LINE.match(line):
            continue  # prose about state is not state
        for name, (_, pattern) in SIGNALS.items():
            hits = len(pattern.findall(line))
            if hits:
                counts[name] = counts.get(name, 0) + hits
                first.setdefault(name, number)
    if len(counts) < MIN_SIGNAL_KINDS:
        return None
    samples = sorted((number, name) for name, number in first.items())[:SAMPLES_PER_FILE]
    return {
        "path": path,
        "score": sum(SIGNALS[name][0] * count for name, count in counts.items()),
        "signals": dict(sorted(counts.items())),
        "samples": [{"line": n, "signal": s, "text": lines[n - 1].strip()} for n, s in samples],
    }


def in_scope(path, scopes):
    return not scopes or any(s == "." or path == s or path.startswith(s + "/") for s in scopes)


def cmd_scan(repo, args):
    scopes = [repo.from_cwd(p) for p in args.path or []]
    scanned, candidates = 0, []
    for path in listed_files(repo):
        if not in_scope(path, scopes) or not is_scannable(path):
            continue
        lines = read_code(repo.path(path))
        if lines is None:
            continue
        scanned += 1
        candidate = score_file(path, lines)
        if candidate:
            candidates.append(candidate)
    candidates.sort(key=lambda c: (-c["score"], c["path"]))
    head = git("-C", repo.root, "rev-parse", "--short", "HEAD")
    print(json.dumps({"head": head.strip() if head else None, "files_scanned": scanned,
                      "candidates": candidates[:args.limit]}, indent=2))


def cmd_signals(repo, args):
    excluded = {"vendor_dirs": VENDOR_DIRS, "output_dirs": OUTPUT_DIRS, "test_dirs": TEST_DIRS,
                "generated_markers": GENERATED_MARKERS, "skipped_suffixes": SKIPPED_SUFFIXES}
    print(json.dumps({"weights": {name: weight for name, (weight, _) in SIGNALS.items()},
                      "excluded": {k: sorted(v) for k, v in excluded.items()}}, indent=2))


# ── check ───────────────────────────────────────────────────────────────────

def findings_path(repo, given):
    return given or repo.path(FINDINGS_PATH)


def load_findings(path):
    try:
        with open(path, encoding="utf-8") as source:
            data = json.load(source)
    except OSError as exc:
        raise UsageError(f"cannot read {path}: {exc.strerror}")
    except json.JSONDecodeError as exc:
        raise UsageError(f"{path} is not valid JSON: {exc}")
    if not isinstance(data, dict) or not isinstance(data.get("findings"), list):
        raise Invalid(f"{path}: the top level must be an object with a `findings` list")
    return data


class Citations:
    """Checks `path[:line[-line]]` references against the tree, counting each file once."""

    def __init__(self, repo):
        self.repo, self.lengths = repo, {}

    def errors(self, where, path, first=None, last=None):
        absolute = self.repo.path(path)
        if not os.path.isfile(absolute):
            return [f"{where}: {path} does not exist"]
        if first is None:
            return []
        if path not in self.lengths:
            with open(absolute, "rb") as source:
                self.lengths[path] = len(source.read().splitlines())
        end = int(last or first)
        if not 1 <= int(first) <= end <= self.lengths[path]:
            return [f"{where}: {path}:{first}{'-' + last if last else ''} is past the end "
                    f"({self.lengths[path]} lines) — the citation is stale"]
        return []

    def of_ref(self, where, ref):
        match = re.fullmatch(r"(.+?)(?::(\d+)(?:-(\d+))?)?", str(ref))
        return self.errors(where, *match.groups())

    def in_text(self, where, text):
        """A bare `word:12` counts only when it looks like a path or names a file (`Makefile:3`)."""
        cited = [m.groups() for m in CITATION.finditer(str(text))
                 if "/" in m[1] or "." in m[1] or os.path.isfile(self.repo.path(m[1]))]
        if not cited:
            return [f"{where} needs a path:line citation"]
        return [e for groups in cited for e in self.errors(where, *groups)]


def path_list_errors(finding, key, citations, required):
    refs = finding[key]
    if not isinstance(refs, list) or (required and not refs):
        return [f"{key} must be a list" + (" with at least one file" if required else "")]
    return [e for ref in refs for e in citations.of_ref(key, ref)]


def edge_errors(finding, key, states, citations, extra=(), required=False):
    edges = finding[key]
    if not isinstance(edges, list) or (required and not edges):
        return [f"{key} must be a list" + (" with at least one transition" if required else "")]
    errors = []
    for i, edge in enumerate(edges, 1):
        where = f"{key}[{i}]"
        needed = EDGE_FIELDS + extra
        if not isinstance(edge, dict) or any(k not in edge for k in needed):
            errors.append(f"{where} needs {', '.join(needed)}")
            continue
        errors += [f"{where}: '{edge[k]}' is not a declared state" for k in ("from", "to") if edge[k] not in states]
        if not isinstance(edge["tested"], bool):
            errors.append(f"{where}.tested must be true or false")
        errors += citations.in_text(f"{where}.via", edge["via"])
    return errors


def finding_errors(finding, citations):
    """Every schema break in one finding, in field order."""
    if not isinstance(finding, dict):
        return ["a finding must be an object"]
    missing = [f"missing field '{f}'" for f in FINDING_FIELDS if f not in finding]
    if missing:
        return missing
    errors, states = [], finding["states"]
    if not (isinstance(states, list) and len(states) >= 2 and len(set(states)) == len(states)):
        errors.append("states must list at least two distinct states")
        states = []
    errors += path_list_errors(finding, "files", citations, required=True)
    errors += path_list_errors(finding, "tests", citations, required=False)
    errors += edge_errors(finding, "transitions", states, citations, required=True)
    errors += edge_errors(finding, "hidden", states, citations, extra=("why",))
    if finding["entry"] not in states:
        errors.append(f"entry '{finding['entry']}' is not a declared state")
    if not isinstance(finding["exit"], list):
        errors.append("exit must be a list of terminal states (empty when none)")
    else:
        errors += [f"exit: '{s}' is not a declared state" for s in finding["exit"] if s not in states]
    if finding["confidence"] not in CONFIDENCE:
        errors.append(f"confidence must be one of {', '.join(CONFIDENCE)}")
    if finding["tested"] not in TESTED:
        errors.append(f"tested must be one of {', '.join(TESTED)}")
    elif finding["tested"] == "TESTED" and not finding["tests"]:
        errors.append("TESTED needs at least one test file in `tests`")
    return errors


def validate(repo, data):
    citations, errors, seen = Citations(repo), [], set()
    for i, finding in enumerate(data["findings"], 1):
        name = finding.get("name") if isinstance(finding, dict) else None
        label = f"finding {i} '{name}'" if name else f"finding {i}"
        errors.extend(f"{label}: {e}" for e in finding_errors(finding, citations))
        if name in seen:
            errors.append(f"{label}: duplicate name — names identify machines across runs")
        seen.add(name)
    if errors:
        raise Invalid("\n".join(errors))


def coverage(finding):
    edges = finding["transitions"] + finding["hidden"]
    return round(sum(e["tested"] for e in edges) / len(edges), 2)


def flags(finding):
    found = []
    if finding["tested"] == "UNTESTED":
        found.append("UNTESTED")
    if finding["hidden"]:
        found.append("HIDDEN_TRANSITIONS")
    if len(finding["states"]) > WIDE_STATES and coverage(finding) < LOW_COVERAGE:
        found.append("WIDE_LOW_COVERAGE")
    if finding["confidence"] == "LOW":
        found.append("LOW_CONFIDENCE")
    return found


def cmd_check(repo, args):
    path = findings_path(repo, args.findings)
    data = load_findings(path)
    validate(repo, data)
    stale = []
    for finding in data["findings"]:
        derived = {"coverage": coverage(finding), "flags": flags(finding)}
        if any(k in finding and finding[k] != v for k, v in derived.items()):
            stale.append(finding["name"])
        finding.update(derived)
        print(f"{finding['confidence']:<6} {finding['name']} — {len(finding['states'])} states, "
              f"{len(finding['transitions'])} transitions, {len(finding['hidden'])} hidden, "
              f"coverage {finding['coverage']:.0%}, flags: {', '.join(finding['flags']) or 'none'}")
    if args.write:
        with open(path, "w", encoding="utf-8") as out:
            json.dump(data, out, indent=2, ensure_ascii=False)
            out.write("\n")
    elif stale:
        raise Invalid(f"stored coverage/flags are stale — re-run with --write: {', '.join(stale)}")


# ── tla ─────────────────────────────────────────────────────────────────────

def module_name(name):
    words = re.findall(r"[A-Za-z0-9]+", name)
    joined = "".join(w[:1].upper() + w[1:] for w in words) or "Machine"
    return joined if joined[0].isalpha() else "M" + joined


def tla_string(text):
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def tla_set(values):
    return "{" + ", ".join(tla_string(v) for v in values) + "}"


def render_tla(finding, module, source):
    """The module text and its TLC config, naming the same operators."""
    type_ok, intended_only = TLA_INVARIANTS
    hidden_vias = [f"hidden {i}: {h['via']}" for i, h in enumerate(finding["hidden"], 1)]
    lines = [
        f"---- MODULE {module} ----",
        f"\\* Skeleton generated by /find-implicit-state-machines from {source}.",
        f"\\* Machine: {finding['name']} (confidence {finding['confidence']}).",
        f"\\* Files: {', '.join(finding['files'])}",
        "\\* One action per transition the code can take; `via` names where it happens.",
        "\\* Before checking: write each rule the reader agrees to as an INVARIANT and add",
        "\\* the variables those rules need. Read the result with /statechart.",
        "EXTENDS TLC",
        "",
        "VARIABLES state, via",
        "vars == <<state, via>>",
        "",
        f"States == {tla_set(finding['states'])}",
        f"HiddenVias == {tla_set(hidden_vias)}",
        "",
        f"{TLA_INIT} == state = {tla_string(finding['entry'])} /\\ via = \"start\"",
        "",
        "\\* Intended transitions",
    ]
    actions = []
    for i, t in enumerate(finding["transitions"], 1):
        actions.append(f"T{i}")
        lines.append(f"T{i} == state = {tla_string(t['from'])} /\\ state' = {tla_string(t['to'])}"
                     f" /\\ via' = {tla_string(t['via'])}")
    if finding["hidden"]:
        lines += ["", "\\* Hidden transitions: paths the code allows that were likely not intended"]
    for i, (h, via) in enumerate(zip(finding["hidden"], hidden_vias), 1):
        actions.append(f"H{i}")
        lines.append("\\* " + " ".join(str(h["why"]).split()))
        lines.append(f"H{i} == state = {tla_string(h['from'])} /\\ state' = {tla_string(h['to'])}"
                     f" /\\ via' = {tla_string(via)}")
    if finding["exit"]:
        actions.append("Done")
        lines += ["", "\\* Exit states stutter, so a correct end is not reported as a deadlock",
                  f"Done == state \\in {tla_set(finding['exit'])} /\\ UNCHANGED vars"]
    disjunction = " \\/ ".join(actions)
    lines += ["", f"{TLA_NEXT} == {disjunction}", "",
              f"{type_ok} == state \\in States",
              "\\* Fails on the shortest path that takes a hidden transition",
              f"{intended_only} == via \\notin HiddenVias", "===="]
    config = [f"INIT {TLA_INIT}", f"NEXT {TLA_NEXT}"] + [f"INVARIANT {n}" for n in TLA_INVARIANTS]
    return "\n".join(lines) + "\n", "\n".join(config) + "\n"


def cmd_tla(repo, args):
    path = findings_path(repo, args.findings)
    data = load_findings(path)
    validate(repo, data)
    finding = next((f for f in data["findings"] if f["name"] == args.name), None)
    if finding is None:
        names = ", ".join(f["name"] for f in data["findings"])
        raise Invalid(f"no finding named '{args.name}' in {path} (have: {names})")
    module = module_name(finding["name"])
    out_dir = args.out or repo.path(TLA_DIR)
    os.makedirs(out_dir, exist_ok=True)
    spec, config = render_tla(finding, module, path)
    for suffix, text in ((".tla", spec), (".cfg", config)):
        with open(os.path.join(out_dir, module + suffix), "w", encoding="utf-8") as out:
            out.write(text)
    print(os.path.join(out_dir, module + ".tla"))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    scan = sub.add_parser("scan", help="rank files by state-like patterns")
    scan.add_argument("--path", action="append", help="limit the scan to this file or directory")
    scan.add_argument("--limit", type=int, default=DEFAULT_LIMIT)
    sub.add_parser("signals", help="print the signal weights and exclusions scan applies")
    check = sub.add_parser("check", help="validate a findings file and compute its flags")
    check.add_argument("findings", nargs="?", help=f"default: <repo root>/{FINDINGS_PATH}")
    check.add_argument("--write", action="store_true", help="store coverage and flags in the file")
    tla = sub.add_parser("tla", help="write a TLA+ skeleton for one machine")
    tla.add_argument("findings", nargs="?", help=f"default: <repo root>/{FINDINGS_PATH}")
    tla.add_argument("--name", required=True)
    tla.add_argument("--out", help=f"default: <repo root>/{TLA_DIR}")
    args = parser.parse_args(argv)
    try:
        {"scan": cmd_scan, "signals": cmd_signals, "check": cmd_check, "tla": cmd_tla}[args.command](Repo(), args)
    except Invalid as exc:
        print(f"state_machines: {exc}", file=sys.stderr)
        return 1
    except UsageError as exc:
        print(f"state_machines: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
